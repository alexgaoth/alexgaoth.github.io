// Writes the homepage's journey: the shots its scroll holds on, in order,
// with every move routed clear of the solid (route.mjs). The page times them
// against its own text (astro/src/lib/qjulia/home.js); the ball that grows
// out of the title and goes back into it is drawn there too.
// usage, from the repo root: node scripts/home-shots/make-home.mjs
// then rebuild (cd astro && npm run build) and look at / on a desktop window.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { route } from './route.mjs';

const OUT = process.argv[2] || fileURLToPath(new URL('../../astro/src/lib/qjulia/homeShots.js', import.meta.url));
// Three views found by a candidate search in the qjulia repo, kept here as
// plain camera states: F15 a fan of ribbons up close, D04 the cut face,
// J20 the webs through a long lens.
const pool = {
  F15: { fov: 72, iter: 26, az: -178.06924576405095, el: -1.577137050637063, dist: 0.8005912134668974, target: [-0.030174073612601292, 0.586842425452215, 0.8386224951230399] },
  D04: { fov: 40, iter: 22, az: 10, el: 10, dist: 1.6, target: [0.3, 0.2, 0], clip: { az: 0, el: 0, w: 0 } },
  J20: { fov: 4.83232936100103, iter: 22, az: 177.1593379788101, el: -5.959630009236902, dist: 9.963202714920044, target: [-0.8835265218102695, 0.42565434580879835, 0.5021566679272402] },
};
const cand = (id) => structuredClone(pool[id]);

const O = [0, 0, 0];
const ALPHA = [-0.327, 0.4837, 0]; // repelling fixed point of z^2 + c, on the z = 0 face
const Z = { az: 0, el: 0, w: 0 };
const zoom = (dist, iter, roll = 0) => ({ az: 0, el: 0, dist, target: ALPHA, fov: 40, iter, roll, clip: Z });
// Radius of the ball the slice becomes when turned 90° in the 1–k plane
// (marched on the CPU: 0.9179 in every direction).
const BALL_RADIUS = 0.9179;

// text: the section whose words hold on this shot. A shot without text is a
// beat: held between sections, no words.
// drift: how far the hold turns per viewport height of scroll; the page
// multiplies it by however long the hold is, so a longer hold turns further
// at the same speed.
// layout: the page centres the shot's target in the free space beside its
// text. fit: the visible radius of a compact shape, so the page can pull the
// camera back when that space is narrow.
const HOME = [
  { id: 'egg', text: 'hi', layout: true, fit: 1.0, st: { az: 50, el: 15, dist: 3.9, target: O, fov: 40, iter: 18, rot4: [70, 0], offset: [0.5, 0.02] }, drift: { ra: -6 } },
  { id: 'whole', text: 'built', layout: true, fit: 1.2, st: { az: 50, el: 10, dist: 4.3, target: O, fov: 40, iter: 18, offset: [0.42, 0] }, drift: { az: 5 } },
  { id: 'fan', text: 'fractal', st: cand('F15'), drift: { dist: -0.025 } },
  { id: 'face', st: { az: 0, el: 0, dist: 1.3, target: O, fov: 60, iter: 26, clip: Z }, drift: { az: 3 }, vias: [zoom(0.55, 44), zoom(0.22, 52, 8), zoom(0.1, 58, 16)] },
  { id: 'spiral', st: zoom(0.05, 64, 24), drift: { roll: 10 } },
  { id: 'cliff', st: { az: 25, el: 35, dist: 0.3, target: ALPHA, fov: 45, iter: 48, clip: Z }, drift: { az: 4 } },
  // the writing view keeps its own framing: centring it left too much air
  { id: 'cutface', text: 'writing', st: { ...cand('D04'), offset: [-0.35, 0] }, drift: { az: 2.5 } },
  { id: 'webs', text: 'doing', layout: true, st: { ...cand('J20'), fov: 8.5, offset: [-0.75, 0.04] }, drift: { az: 0.6 } },
  { id: 'ball', st: { az: 50, el: 15, dist: 8, target: O, fov: 40, iter: 18, rot4: [90, 0] } },
].map((s) => ({ drift: {}, vias: [], ...s }));

// Routing checks each move from where its hold ends, so it needs whole-hold
// drifts: about 2.4 viewports for a section, 0.8 for a beat.
const perVh = HOME.map((s) => s.drift);
HOME.forEach((s) => { const k = s.text ? 2.4 : 0.8; s.drift = Object.fromEntries(Object.entries(s.drift).map(([f, v]) => [f, v * k])); });
route(HOME);
HOME.forEach((s, i) => { s.drift = perVh[i]; });

const r4 = (v) => (typeof v === 'number' ? +v.toFixed(4) : Array.isArray(v) ? v.map(r4) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, r4(x)])) : v);
writeFileSync(OUT, `// The homepage's journey, in scroll order. Generated by
// scripts/home-shots/make-home.mjs, which routes every move clear of the
// solid; edit there. drift is per viewport height of scroll.
export const BALL_RADIUS = ${BALL_RADIUS};
export const HOME_SHOTS = ${JSON.stringify(r4(HOME.map(({ id, text, layout, fit, st, drift, vias }) => ({ id, ...(text ? { text } : {}), ...(layout ? { layout } : {}), ...(fit ? { fit } : {}), st, drift, vias }))), null, 1)};
`);
console.log(HOME.length, 'shots written to', OUT);
